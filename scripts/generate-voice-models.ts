/**
 * Writes `src/voice-models.generated.ts` from the two singer meshes in
 * `assets/`: each one's strokes, in millimetres (`glb-strokes.ts`), and
 * its map icon, the front silhouette (`silhouette-icon.ts`).
 *
 *   bun run generate:voices
 */
import fs from 'node:fs';
import path from 'node:path';
import { meshStrokes, readMesh } from './glb-strokes';
import { silhouetteIcon } from './silhouette-icon';

const ROOT = path.resolve(import.meta.dir, '..');
const OUT = path.join(ROOT, 'src/voice-models.generated.ts');

const PERFORMERS = [
  { constant: 'MALE_VOCALIST', id: 'male-vocalist', file: 'male_singer.glb' },
  { constant: 'FEMALE_VOCALIST', id: 'female-vocalist', file: 'female_singer.glb' },
] as const;

const blocks: string[] = [];
for (const { constant, id, file } of PERFORMERS) {
  const mesh = readMesh(path.join(ROOT, 'assets', file));
  // Every edge of the mesh, as modelled: nothing thinned or simplified.
  const strokes = meshStrokes(mesh);
  const millimetres = strokes.map(stroke => stroke.flatMap(p => p.map(c => Math.round(c * 1000))));
  const segments = millimetres.reduce((n, s) => n + s.length / 3 - 1, 0);
  const shapes = silhouetteIcon(mesh);
  console.log(`${file}: ${strokes.length} strokes, ${segments} segments, ${shapes.length} icon outlines`);

  blocks.push(
    `/** \`assets/${file}\`: ${strokes.length} strokes, ${segments} segments. */\n` +
      `export const ${constant}_STROKES_MM: readonly (readonly number[])[] = ${JSON.stringify(millimetres)};\n\n` +
      `export const ${constant}_ICON: InstrumentIconArt = ${JSON.stringify({ name: id, shapes })};\n`
  );
}

fs.writeFileSync(
  OUT,
  `// Generated by scripts/generate-voice-models.ts from assets/*.glb. Do not edit.\n` +
    `import type { InstrumentIconArt } from '@sudobility/music_types';\n\n` +
    blocks.join('\n')
);
console.log(`wrote ${path.relative(ROOT, OUT)}`);
